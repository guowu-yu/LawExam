# ============ 刑法总则 ============
xingfa_zongze = r"""
## 一、学科定位
刑法总则是犯罪论与刑罚论的基石，客观题 30–40 分，主观题分析起点。重点：犯罪构成、正当防卫、犯罪形态、共同犯罪、罪数、刑罚裁量。

## 二、法条原文索引
- **第 13 条（但书）**：情节显著轻微危害不大的，不认为是犯罪。
- **第 14 条**：明知自己的行为会发生危害社会的结果，并且希望或放任，是故意犯罪。
- **第 15 条**：应当预见而未预见（疏忽大意）或已预见而轻信避免（过于自信），是过失犯罪。
- **第 20 条（正当防卫）**：为制止不法侵害，对不法侵害人造成损害的，不负刑事责任；明显超过必要限度造成重大损害的，应负刑事责任，但应减轻或免除；对行凶、杀人、抢劫、强奸、绑架等严重危及人身安全的暴力犯罪，防卫无过当（特殊防卫）。
- **第 22–24 条（犯罪形态）**：预备、未遂（已着手未得逞）、中止（自动放弃或有效防止结果）。
- **第 25 条（共犯）**：二人以上共同故意犯罪。
- **第 67 条（自首）**：自动投案并如实供述，可从轻或减轻；犯罪较轻可免除。
- **第 232 条（故意杀人）**：处死刑、无期或 10 年以上；情节较轻 3–10 年。

## 三、犯罪构成（两阶层路径）
```
不法（客观要件 + 客观阻却事由）
├─ 行为、对象、结果、因果关系
└─ 正当防卫、紧急避险
责任（主观要件 + 主观阻却事由）
├─ 故意、过失、目的
└─ 责任能力、违法性认识、期待可能性
```
**四要件路径**：犯罪客体、客观方面、主体、主观方面。两种路径法考均接受，重点是实质判断。

## 四、正当行为
| 类型 | 要件 | 限度 |
|---|---|---|
| 正当防卫 | 不法侵害正在进行、针对侵害人、防卫意图 | 必要限度；特殊防卫无过当 |
| 紧急避险 | 危险正在发生、不得已、损害较小法益 | 避险过当应担责 |
| 被害人承诺 | 法益可处分、真实意思、范围限度内 | 生命不可承诺 |

## 五、犯罪形态
- **预备**：为犯罪准备工具、制造条件，因意志外原因未着手。
- **未遂**：已着手实行，因意志外原因未得逞。
- **中止**：自动放弃犯罪或有效防止结果（"能达目的而不欲"）。
- **既遂**：具备全部构成要件。

**着手标准**：行为对法益产生现实、紧迫危险。

## 六、共同犯罪
- 主体：二人以上；责任能力；共同故意。
- 分类：主犯、从犯（应当从轻减轻或免除）、胁从犯、教唆犯。
- **承继共犯**：中途加入者对加入后行为负责。
- **共犯脱离**：有效切断因果联系方可脱离。
- **片面共犯**：片面对向帮助（如片面帮助犯）可成立。

## 七、罪数形态
- **想象竞合**：一行为触犯数罪名，从一重。
- **牵连犯**：手段与目的牵连，一般从一重。
- **吸收犯**：重行为吸收轻行为。
- **数罪并罚**：法定情形（如判决宣告后发现漏罪、又犯新罪）。

## 八、刑罚裁量
- 量刑情节：自首、立功（揭发他人犯罪属实可从轻减轻；重大立功可减轻或免除）、累犯（应当从重）、坦白。
- **死刑适用限制**：犯罪时不满 18、审判时怀孕妇女、审判时已满 75（以特别残忍手段致人死亡除外）不适用死刑。

## 九、典型案例与真题
**【2023-客观】** 甲持刀杀乙，乙逃，甲追至河边乙跳河溺亡。甲的行为与死亡有无因果？
- A. 无因果，乙自己跳河
- B. 有因果，甲追杀致乙处于危险
- C. 意外事件
- D. 甲仅成立预备
**答案 B**。解析：甲的追杀行为使乙陷入紧迫危险，跳河是合理反应，因果关系不中断，甲对死亡结果负责（故意杀人既遂）。

**【2021-客观】** 甲盗窃后被发现，为逃跑将抓捕者打成轻伤。甲构成？
- A. 盗窃与故意伤害数罪
- B. 转化抢劫（第 269 条）
- C. 仅盗窃
- D. 仅故意伤害
**答案 B**。解析：盗窃后为窝藏赃物、抗拒抓捕、毁灭罪证而当场使用暴力或以暴力相威胁，转化为抢劫罪（第 269 条）。

## 十、易错高频
1. **正当防卫 vs 防卫过当**：特殊防卫（行凶杀人等）无过当。
2. **犯罪中止"自动性"**：能而不欲 vs 欲而不能（未遂）。
3. **转化抢劫**（第 269 条）是高频。
4. **自首**：自动投案 + 如实供述，被采取强制措施后如实供述同种罪行不属自首但可坦白。
5. **间接故意 vs 过于自信过失**：有无避免结果的措施与认识。

## 十一、自测清单
- [ ] 两阶层/四要件能运用
- [ ] 正当防卫要件与特殊防卫
- [ ] 预备/未遂/中止区分
- [ ] 共犯分类与脱离
- [ ] 转化抢劫（第 269 条）
- [ ] 自首立功累犯规则
"""

